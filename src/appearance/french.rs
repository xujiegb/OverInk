#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compact_buttons_and_messages() {
        for (english, french) in [
            ("Settings", "Réglages"),
            ("Highlighter", "Surligneur"),
            ("Pick screen", "Pipette"),
            ("System keyboard", "Clavier système"),
            ("Save As…", "Enregistrer sous…"),
            ("Cancel", "Annuler"),
        ] {
            assert_eq!(short(english), french);
        }
        assert_eq!(short("unmapped plugin text"), "unmapped plugin text");
    }
}
